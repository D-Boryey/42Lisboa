#include "libft.h"

void	*ft_calloc(unsigned int nmemb, unsigned int size)
{
	char	*dest;
	unsigned int	total;

	total = nmemb * size;
	dest = malloc(total);
	if (!dest)
		return (NULL);
	ft_memset(dest, 0, total);
	return (dest);
}
